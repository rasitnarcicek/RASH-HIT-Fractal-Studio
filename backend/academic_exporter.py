def export_academic_package_v3(
    model: AnalysisReportModel,
    output_root: Path,
    generate_data_maps: bool = False,
    generate_raw_csv: bool = False,
    profile: Optional[Union[OutputProfile, str]] = None,
    skipped_outputs: Optional[List[Dict[str, Any]]] = None,
    measure_mode: str = 'area'
) -> Path:
    if profile is None:
        profile = load_output_profile("lean")
    elif isinstance(profile, str):
        profile = load_output_profile(profile)

    safe_stem = model.safe_name
    out_dir = output_root / safe_stem

    # Wipe existing output directory completely
    if out_dir.exists():
        shutil.rmtree(out_dir, ignore_errors=True)
    out_dir.mkdir(parents=True, exist_ok=True)

    out_dir_fig = out_dir / "figures"
    out_dir_tables = out_dir / "tables"
    out_dir_excel = out_dir / "excel"
    out_dir_report = out_dir / "report"
    out_dir_manifest = out_dir / "manifest"
    out_dir_terminal = out_dir / "terminal"
    out_dir_data = out_dir / "data"
    out_dir_ascii = out_dir / "ascii"

    if profile.generate_map_svgs or profile.generate_map_svgs_legacy:
        out_dir_fig.mkdir(parents=True, exist_ok=True)
    if profile.generate_xlsx_tables or profile.generate_tables_html or profile.generate_levels_csv or profile.generate_levels_json:
        out_dir_tables.mkdir(parents=True, exist_ok=True)
    if profile.generate_workbook:
        out_dir_excel.mkdir(parents=True, exist_ok=True)
    if profile.generate_html_report or profile.generate_pdf_report or profile.generate_markdown_report:
        out_dir_report.mkdir(parents=True, exist_ok=True)
    if profile.generate_manifest:
        out_dir_manifest.mkdir(parents=True, exist_ok=True)
    if profile.generate_terminal_log:
        out_dir_terminal.mkdir(parents=True, exist_ok=True)
    if profile.generate_masks or profile.generate_rle or profile.generate_summary_json or profile.generate_raw_csv or generate_raw_csv:
        out_dir_data.mkdir(parents=True, exist_ok=True)
    if profile.generate_ascii or profile.generate_ascii_book:
        out_dir_ascii.mkdir(parents=True, exist_ok=True)

    # 1. Per-level SVGs
    if profile.generate_map_svgs or profile.generate_map_svgs_legacy:
        for lvl in model.levels:
            generate_pure_vector_svg(lvl, model, out_dir_fig, profile=profile)

    # 2. Master Tables & Technical XLSX Tables
    generate_master_table_files(model, out_dir_tables, out_dir_data, generate_raw_csv=generate_raw_csv, profile=profile)

    # 3. Single Interactive Table Viewer
    if profile.generate_tables_html:
        generate_interactive_table_viewer(model, out_dir_tables)

    # 4. ASCII Maps & Book
    if profile.generate_ascii:
        for lvl in model.levels:
            generate_ascii_files(lvl, safe_stem, out_dir_ascii)
    if profile.generate_ascii_book:
        generate_all_levels_ascii_book(model, out_dir_ascii)

    # 5. Lean Excel Workbook
    if profile.generate_workbook:
        generate_excel_workbook(model, out_dir_excel, generate_data_maps=generate_data_maps)

    # 6. Reports
    if profile.generate_html_report:
        generate_academic_html_report(model, out_dir_report)
    if profile.generate_markdown_report:
        generate_markdown_report(model, out_dir_report)
    if profile.generate_pdf_report:
        generate_pdf_report(model, out_dir_report)

    # 7. Terminal Logs
    if profile.generate_terminal_log:
        generate_terminal_log(model, out_dir_terminal)

    # Remove any empty subfolders
    for sub in ["ascii", "data", "debug", "figures", "tables", "excel", "report", "terminal", "manifest"]:
        sub_p = out_dir / sub
        if sub_p.exists() and sub_p.is_dir():
            if not any(sub_p.rglob("*")):
                shutil.rmtree(sub_p, ignore_errors=True)

    # 8. Manifest SHA-256 JSON
    if profile.generate_manifest:
        out_dir_manifest.mkdir(parents=True, exist_ok=True)
        manifest_files = []
        for p in sorted(out_dir.rglob("*")):
            if p.is_file():
                if p.name.startswith("~$") or p.name.endswith(".tmp") or p.name.endswith(".lock"):
                    continue
                sha = compute_sha256(p)
                rel_p = p.relative_to(out_dir).as_posix()
                category = rel_p.split('/')[0] if '/' in rel_p else "root"
                manifest_files.append({
                    "path": rel_p,
                    "category": category,
                    "size_bytes": p.stat().st_size,
                    "sha256": sha
                })

        man_data = {
            "project": {
                "name": "RASH-HIT Fractal Studio",
                "version": "1.0.0",
                "license": "Apache-2.0",
                "repository": "https://github.com/rasitnarcicek/RASH-HIT-Fractal-Studio",
                "author": "Mehmet Raşit Narçiçek",
                "orcid": "https://orcid.org/0009-0005-3423-255X",
                "citation_file": "CITATION.cff"
            },
            "analysis": {
                "motif": model.motif,
                "safe_name": safe_stem,
                "profile": profile.name,
                "generated_at": model.generated_at,
                "engine": model.analysis_engine,
                "measure_mode": measure_mode,
                "levels": len(model.levels),
                "db": model.db,
                "r2": model.r2
            },
            "runtime_environment": {
                "software_version": "1.0.0",
                "engine": model.analysis_engine,
                "measure": measure_mode,
                "levels": len(model.levels),
                "shapely_version": "2.0+",
                "engine_available": True,
                "hardware_info": model.hardware_info
            },
            "skipped_outputs": skipped_outputs if skipped_outputs else [],
            "integrity": {
                "hash_algorithm": "SHA-256",
                "note": "SHA-256 is used for file integrity verification, not licensing."
            },
            "files": manifest_files
        }
        (out_dir_manifest / "manifest.json").write_text(json.dumps(man_data, indent=2), encoding="utf-8")

    return out_dir
