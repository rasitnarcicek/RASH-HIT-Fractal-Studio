        card_lines.append('    </g>')
        card_lines.append(f'    <g id="grid_overlay" stroke="{stroke_col}" stroke-width="{stroke_w:.2f}">')
        for c in range(cols + 1):
            x = c * cw
            card_lines.append(f'      <line x1="{x:.4f}" y1="0" x2="{x:.4f}" y2="{vh:.4f}"/>')
        for r in range(rows + 1):
            y = r * ch
            card_lines.append(f'      <line x1="0" y1="{y:.4f}" x2="{vw:.4f}" y2="{y:.4f}"/>')
