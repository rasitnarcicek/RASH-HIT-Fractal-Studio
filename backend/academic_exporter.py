def format_aligned_ascii_map(cols: int, rows: int, filled_set: set) -> list[str]:
    """Generates an ASCII/TXT grid matrix with aligned vertical formatting between header and data cells."""
    row_lbl_w = max(4, len(str(rows)) + 1)

    if cols <= 32:
        col_hdr_str = "".join(f" C{c+1:02d}" for c in range(cols))
        def fmt_row(r):
            return "".join("  1 " if (c, r) in filled_set else "  0 " for c in range(cols))
        hdr_lines = [f"{'':>{row_lbl_w}} | {col_hdr_str}"]
    elif cols <= 64:
        col_hdr_str = "".join(f"C{c+1:02d}" for c in range(cols))
        def fmt_row(r):
            return "".join(" 1 " if (c, r) in filled_set else " 0 " for c in range(cols))
        hdr_lines = [f"{'':>{row_lbl_w}} | {col_hdr_str}"]
    else:
        tens = "".join(str(((c + 1) // 10) % 10) if (c + 1) >= 10 else " " for c in range(cols))
        ones = "".join(str((c + 1) % 10) for c in range(cols))
        def fmt_row(r):
            return "".join("1" if (c, r) in filled_set else "0" for c in range(cols))
        hdr_lines = [
            f"{'':>{row_lbl_w}} | {tens}",
            f"{'':>{row_lbl_w}} | {ones}"
        ]

    sep_w = max(72, len(hdr_lines[0]))
    sep_line = "=" * sep_w

    lines = []
    lines.extend(hdr_lines)
    lines.append("-" * len(hdr_lines[0]))

    for r in range(rows):
        lbl = f"R{r+1:0{row_lbl_w-1}d}"
        lines.append(f"{lbl:>{row_lbl_w}} | {fmt_row(r)}")

    lines.append(sep_line)
    return lines

def generate_ascii_files(lvl: LevelReportModel, safe_stem: str, out_dir_ascii: Path) -> Path:
    cols, rows = lvl.cols, lvl.rows
    filled_set = lvl.filled_set
    lvl_fmt = f"{lvl.level:02d}"

    header_lines = [
        "RASH-HIT Fractal Studio v1.0.0 - ASCII OCCUPANCY MAP",
        f"Motif  : {safe_stem}.svg",
        f"Level  : {lvl_fmt}    Grid : {cols} cols x {rows} rows",
        f"Filled : {lvl.filled_cells:,}    Empty : {lvl.empty_cells:,}    Total : {lvl.total_cells:,}",
        f"Fill % : {lvl.occupancy_percent:.2f}%",
        "=" * 72,
    ]

    matrix_lines = format_aligned_ascii_map(cols, rows, filled_set)
    full_lines = header_lines + matrix_lines

    p = out_dir_ascii / f"{lvl_fmt}_{cols}x{rows}_ascii.txt"
    p.write_text("\n".join(full_lines), encoding="utf-8-sig")
    return p

